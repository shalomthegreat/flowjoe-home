// Writes one page per film (watch/<id>/index.html): the Watch page, starting on that film, with the
// film's own picture, title and line for link previews in messages and posts.
// Run after adding or changing a film in js/watch.js, or after editing watch/index.html:   node scripts/build-watch-film-pages.mjs
// Check they are up to date (exit 1 if not):             node scripts/build-watch-film-pages.mjs --check
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(path.join(root, "js/watch.js"), "utf8");
const pick = (re, what) => {
  const m = re.exec(source);
  if (!m) throw new Error(`js/watch.js: could not find ${what}`);
  return m[1];
};
const MEDIA = pick(/const MEDIA = "([^"]+)";/, "MEDIA");
const VERSION = pick(/const VERSION = "([^"]+)";/, "VERSION");
const FILMS = new Function(`return ${pick(/const FILMS = (\[[\s\S]*?\n  \]);/, "FILMS")}`)();

const esc = (text) => text.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const template = fs.readFileSync(path.join(root, "watch/index.html"), "utf8");

// Each film page is the Watch page itself with that film's details in the head and in the first view,
// so a link preview shows the film and nothing has to redirect. js/watch.js reads the film from the address.
function page(film) {
  const url = `https://flowjoe.app/watch/${film.id}/`;
  const title = esc(`${film.title} — a FlowJoe short film`);
  const line = esc(film.line);
  const image = `${MEDIA}${film.id}-wide.jpg?v=${VERSION}`;
  let html = template;
  const set = (re, to) => {
    if (!re.test(html)) throw new Error(`watch/index.html: nothing matches ${re}`);
    html = html.replace(re, to);
  };
  set(/<title>[^<]*<\/title>/, `<!-- Generated by scripts/build-watch-film-pages.mjs from watch/index.html and js/watch.js. Do not edit by hand. -->\n  <title>${title}</title>`);
  set(/(<meta name="description" content=")[^"]*"/, `$1${line}"`);
  set(/(<link rel="canonical" href=")[^"]*"/, `$1${url}"`);
  set(/(<meta property="og:type" content=")[^"]*"/, `$1video.other"`);
  set(/(<meta property="og:url" content=")[^"]*"/, `$1${url}"`);
  set(/(<meta property="og:title" content=")[^"]*"/, `$1${title}"`);
  set(/(<meta property="og:description" content=")[^"]*"/, `$1${line}"`);
  set(/(<meta property="og:image" content=")[^"]*"/, `$1${image}"`);
  set(/(<meta property="og:image:type" content=")[^"]*"/, `$1image/jpeg"`);
  set(/(<meta property="og:image:width" content=")[^"]*"/, `$11280"`);
  set(/(<meta property="og:image:height" content=")[^"]*"/, `$1720"`);
  set(/(<meta property="og:image:alt" content=")[^"]*"/, `$1${title}"`);
  set(/(<meta name="twitter:title" content=")[^"]*"/, `$1${title}"`);
  set(/(<meta name="twitter:description" content=")[^"]*"/, `$1${line}"`);
  set(/(<meta name="twitter:image" content=")[^"]*"/, `$1${image}"`);
  set(/(<meta name="twitter:image:alt" content=")[^"]*"/, `$1${title}"`);
  set(/(<h2 id="info-title">)[^<]*</, `$1${esc(film.title)}<`);
  set(/(id="film-now" aria-hidden="true">)[^<]*</, `$1${esc(film.title)}<`);
  set(/(<p id="info-line">)[^<]*</, `$1${line}<`);
  set(/(<span class="w-meta" id="info-meta">)[^<]*</, `$1${film.dur} · Widescreen<`);
  return html;
}

const check = process.argv.includes("--check");
let stale = 0;
for (const film of FILMS) {
  const file = path.join(root, "watch", film.id, "index.html");
  const want = page(film);
  const have = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (have === want) continue;
  stale += 1;
  if (check) { console.error(`out of date: watch/${film.id}/index.html`); continue; }
  fs.mkdirSync(path.dirname(file), {recursive: true});
  fs.writeFileSync(file, want);
  console.log(`wrote watch/${film.id}/index.html`);
}
const known = new Set(FILMS.map((f) => f.id));
for (const entry of fs.readdirSync(path.join(root, "watch"), {withFileTypes: true})) {
  if (entry.isDirectory() && !known.has(entry.name)) { stale += 1; console.error(`no film for watch/${entry.name}/ (remove it by hand)`); }
}
if (check && stale) process.exit(1);
console.log(check ? "film pages are up to date" : `${FILMS.length} film pages current`);
